#!/usr/bin/env python3
"""Publish the in-app legal docs as static web pages.

assets/docs/privacy_policy.md   -> web/privacy/index.html
assets/docs/terms_of_service.md -> web/terms/index.html

The Markdown files stay the single source of truth (the app shows them in
Settings). Stripe's public details and the app stores need these as public
URLs. Run after editing either file:

    python3 scripts/build_legal_pages.py

No dependencies: it handles only the Markdown these files use (headings,
paragraphs, bullet and numbered lists, **bold**, *italic*, `code`, links).
"""
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = [
    ("assets/docs/privacy_policy.md", "web/privacy/index.html", "Privacy Policy"),
    ("assets/docs/terms_of_service.md", "web/terms/index.html", "Terms of Service"),
]
SITE = "https://evenhalf.app"


def inline(text: str) -> str:
    text = html.escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![*\w])\*(?!\s)(.+?)(?<!\s)\*(?![*\w])", r"<em>\1</em>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', text)
    # Bare URLs and emails (not already inside a tag attribute).
    text = re.sub(r'(?<![">])(https?://[^\s<)]+[^\s<).,])', r'<a href="\1">\1</a>', text)
    text = re.sub(r"(?<![\w:/.\">])([\w.+-]+@[\w-]+\.[\w.]+[\w])", r'<a href="mailto:\1">\1</a>', text)
    return text


def to_html(md: str) -> str:
    out, para, list_tag = [], [], None

    def flush_para():
        if para:
            out.append("<p>" + inline(" ".join(para)) + "</p>")
            para.clear()

    def close_list():
        nonlocal list_tag
        if list_tag:
            out.append(f"</{list_tag}>")
            list_tag = None

    for raw in md.splitlines():
        line = raw.rstrip()
        stripped = line.strip()
        m_h = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        m_ul = re.match(r"^[-*]\s+(.*)$", stripped)
        m_ol = re.match(r"^\d+\.\s+(.*)$", stripped)
        if not stripped:
            flush_para()
            close_list()
        elif stripped in ("---", "***"):
            flush_para()
            close_list()
            out.append("<hr>")
        elif m_h:
            flush_para()
            close_list()
            level = len(m_h.group(1))
            out.append(f"<h{level}>{inline(m_h.group(2))}</h{level}>")
        elif m_ul or m_ol:
            flush_para()
            tag = "ul" if m_ul else "ol"
            if list_tag != tag:
                close_list()
                out.append(f"<{tag}>")
                list_tag = tag
            out.append("<li>" + inline((m_ul or m_ol).group(1)) + "</li>")
        elif list_tag and raw.startswith((" ", "\t")):
            # Continuation of the previous list item.
            out[-1] = out[-1][: -len("</li>")] + " " + inline(stripped) + "</li>"
        else:
            close_list()
            para.append(stripped)
    flush_para()
    close_list()
    return "\n".join(out)


TEMPLATE = """<!DOCTYPE html>
<!-- Generated by scripts/build_legal_pages.py from {src}. Edit the Markdown, not this file. -->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{title} · EvenHalf</title>
  <meta name="description" content="EvenHalf {title}.">
  <link rel="canonical" href="{site}/{slug}/">
  <link rel="icon" type="image/png" href="/favicon.png">
  <style>
    :root {{ --bg: #ffffff; --fg: #1f2937; --muted: #6b7280; --accent: #4f46e5; --line: #e5e7eb; }}
    @media (prefers-color-scheme: dark) {{
      :root {{ --bg: #0f1115; --fg: #e5e7eb; --muted: #9ca3af; --accent: #a5b4fc; --line: #262a33; }}
    }}
    * {{ box-sizing: border-box; }}
    body {{ margin: 0; background: var(--bg); color: var(--fg);
      font: 16px/1.65 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; }}
    .wrap {{ max-width: 760px; margin: 0 auto; padding: 24px 16px 64px; }}
    header {{ display: flex; justify-content: space-between; align-items: center; margin-bottom: 24px; }}
    .brand {{ display: flex; gap: 8px; align-items: center; font-weight: 700; color: var(--fg); text-decoration: none; }}
    a {{ color: var(--accent); overflow-wrap: anywhere; }}
    h1 {{ font-size: 32px; line-height: 1.2; }}
    h2 {{ font-size: 22px; margin-top: 36px; padding-top: 12px; border-top: 1px solid var(--line); }}
    h3 {{ font-size: 18px; margin-top: 24px; }}
    code {{ font-size: 0.9em; }}
    footer {{ margin-top: 48px; color: var(--muted); font-size: 14px; }}
  </style>
</head>
<body>
  <div class="wrap">
    <header>
      <a class="brand" href="/welcome/"><img src="/icons/Icon-192.png" alt="" width="28" height="28">EvenHalf</a>
      <a href="/">Open the app</a>
    </header>
    <main>
{body}
    </main>
    <footer><a href="/welcome/">Home</a> · <a href="/privacy/">Privacy</a> · <a href="/terms/">Terms</a></footer>
  </div>
</body>
</html>
"""


def main() -> None:
    for src, dest, title in PAGES:
        body = to_html((ROOT / src).read_text(encoding="utf-8"))
        slug = Path(dest).parent.name
        page = TEMPLATE.format(src=src, title=title, site=SITE, slug=slug, body=body)
        out = ROOT / dest
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(page, encoding="utf-8")
        print(f"wrote {dest}")


if __name__ == "__main__":
    main()
